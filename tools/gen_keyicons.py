"""Generate firmware/ips/reactive_keyicons.h from profiles/keys.json.

The native profile keeps one dot-matrix icon per special key (Enter, Backspace, Space,
arrows, PgUp/PgDn/Home/End, Windows, A). The base screen already shows these via the
stock icon cache; the interactive key panel reuses the same bitmaps so both UIs agree.

Output: a flat bit-packed blob + a small table {key,w,h,offset}. Icons are drawn scaled
to fit the panel by the firmware.

Usage: .venv/Scripts/python.exe tools/gen_keyicons.py
SPDX-License-Identifier: MIT.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'profiles/keys.json'
OUT = ROOT / 'firmware/ips/reactive_keyicons.h'


def main():
    data = json.loads(SRC.read_text(encoding='utf8'))
    # Keep only the icons the panel really benefits from; letters/labels fall back to
    # the pixel font, and dropping the rest keeps the 4976 B append region in budget.
    skip = {4, 42, 44, 74, 75, 77, 78}
    glyphs = [g for g in data['glyphs'] if g['key'] not in skip]
    blob = bytearray()
    table = []
    for g in glyphs:
        rows = g['rows']
        h = len(rows)
        w = max(len(r) for r in rows)
        if w > 255 or h > 255:
            raise SystemExit('icon too large: %s' % g['name'])
        off = len(blob)
        stride = (w + 7) // 8
        need = stride * h
        blob.extend(b'\0' * need)
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == '1':
                    pos = off + y * stride + (x >> 3)
                    blob[pos] |= 0x80 >> (x & 7)
        table.append((g['key'], w, h, off))

    lines = ['/* SPDX-License-Identifier: MIT; generated by tools/gen_keyicons.py',
             ' * from profiles/keys.json (native key icons). Do not edit by hand. */',
             '#ifndef REACTIVE_KEYICONS_H',
             '#define REACTIVE_KEYICONS_H',
             'typedef struct {u16 key; u8 w, h; u16 off;} PxKeyIcon;',
             '#define PX_KEY_ICON_COUNT %d' % len(table),
             'static const unsigned char px_key_icon_bits[]={']
    for i in range(0, len(blob), 16):
        chunk = blob[i:i + 16]
        lines.append(' ' + ','.join('0x%02x' % b for b in chunk) + ',')
    lines.append('};')
    lines.append('static const PxKeyIcon px_key_icons[]={')
    for key, w, h, off in table:
        lines.append(' {%du,%du,%du,%du},' % (key, w, h, off))
    lines.append('};')
    lines.append('#endif /* REACTIVE_KEYICONS_H */')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf8')
    print('wrote %s: %d icons, %d bytes' % (OUT, len(table), len(blob)))


if __name__ == '__main__':
    main()
